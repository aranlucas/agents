func object(name string, value any, groups ...[]fieldDef) objectDef {
	var result []fieldDef
	for _, group := range groups {
		result = append(result, group...)
	}
	return objectDef{Name: name, GoType: reflect.TypeOf(value), Fields: result}
}

func field(name, tsType string, optional bool) fieldDef {
	return fieldDef{JSONName: name, TSType: tsType, Optional: optional}
}

func fields(values ...fieldDef) []fieldDef { return values }

func required(names ...string) []fieldDef {
	result := make([]fieldDef, 0, len(names))
	for _, name := range names {
		result = append(result, field(name, "", false))
	}
	return result
}

func optional(names ...string) []fieldDef {
	result := make([]fieldDef, 0, len(names))
	for _, name := range names {
		result = append(result, field(name, "", true))
	}
	return result
}

func stateFields(values ...fieldDef) []fieldDef { return values }

func quotedUnion(values []string) string {
	quoted := make([]string, 0, len(values))
	for _, value := range values {
		quoted = append(quoted, fmt.Sprintf("%q", value))
	}
	return strings.Join(quoted, " | ")
}

func typeScriptProperty(value string) string {
	for index, r := range value {
		if (r >= 'a' && r <= 'z') || (r >= 'A' && r <= 'Z') || r == '_' || r == '$' || (index > 0 && r >= '0' && r <= '9') {
			continue
		}
		return fmt.Sprintf("%q", value)
	}
	return value
}

func generateShellRoutes() []byte {
	var out bytes.Buffer
	out.WriteString("# Code generated by go run ./cmd/contracts; DO NOT EDIT.\n")
	out.WriteString("agent_routes=(")
	for index, spec := range catalog.All() {
		if index > 0 {
			out.WriteByte(' ')
		}
		out.WriteString(spec.Route)
	}
	out.WriteString(")\n")
	return out.Bytes()
}

func repoRoot() (string, error) {
	dir, err := os.Getwd()
	if err != nil {
		return "", err
	}
	for {
		if isDir(filepath.Join(dir, "cmd", "contracts")) && isFile(filepath.Join(dir, "go.mod")) {
			return dir, nil
		}
		parent := filepath.Dir(dir)
		if parent == dir {
			return "", errors.New("repository root not found")
		}
		dir = parent
	}
}

func isDir(path string) bool {
	info, err := os.Stat(path)
	return err == nil && info.IsDir()
}

func isFile(path string) bool {
	info, err := os.Stat(path)
	return err == nil && !info.IsDir()
}

func fatal(err error) {
	fmt.Fprintln(os.Stderr, err)
	os.Exit(1)
}
