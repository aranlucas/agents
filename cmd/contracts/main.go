const generatedHeader = "// Code generated by go run ./cmd/contracts; DO NOT EDIT.\n"

type enumDef struct {
	Name   string
	Values []string
}

type fieldDef struct {
	JSONName string
	TSType   string
	Optional bool
}

type objectDef struct {
	Name   string
	GoType reflect.Type
	Fields []fieldDef
}

func main() {
	typescriptOutput := flag.String("typescript-output", "", "optional output path for a TypeScript client projection")
	check := flag.Bool("check", false, "fail when checked-in generated contracts are stale")
	flag.Parse()

	root, err := repoRoot()
	if err != nil {
		fatal(err)
	}
	outputs, err := generatedOutputs()
	if err != nil {
		fatal(err)
	}
	if *typescriptOutput != "" {
		projection, err := generateTypeScript()
		if err != nil {
			fatal(err)
		}
		outputs[*typescriptOutput] = projection
	}
	for relative, content := range outputs {
		path := relative
		if !filepath.IsAbs(path) {
			path = filepath.Join(root, path)
		}
		if *check {
			current, readErr := os.ReadFile(path)
			if readErr != nil {
				fatal(fmt.Errorf("read generated contract %s: %w", relative, readErr))
			}
			if !bytes.Equal(current, content) {
				fatal(fmt.Errorf("generated contract %s is stale; run go run ./cmd/contracts", relative))
			}
			continue
		}
		if err := os.MkdirAll(filepath.Dir(path), 0o755); err != nil {
			fatal(err)
		}
		if err := os.WriteFile(path, content, 0o644); err != nil {
			fatal(err)
		}
	}
}

func generatedOutputs() (map[string][]byte, error) {
	outputs := map[string][]byte{
		"scripts/generated-agent-routes.sh": generateShellRoutes(),
	}

	schemas, err := generateJSONSchemas()
	if err != nil {
		return nil, err
	}
	maps.Copy(outputs, schemas)
	return outputs, nil
}

func generateJSONSchemas() (map[string][]byte, error) {
	objects := make(map[string]objectDef)
	objectsByType := make(map[reflect.Type]objectDef)
	for _, object := range objectDefinitions() {
		objects[object.Name] = object
		objectsByType[object.GoType] = object
	}
	stateNames := map[string]string{
		"travel": "TripState", "grocery": "GroceryState", "fitness": "FitnessState",
		"wellness": "WellnessState", "expense": "ExpenseState", "oral-boards": "OralBoardsState",
		"trends": "TrendsState", "research": "ResearchState",
		"jobs": "JobsState", "interview": "InterviewState",
		"spreadsheet": "SpreadsheetState", "presentation": "PresentationState",
	}
	outputs := make(map[string][]byte, len(stateNames))
	for _, spec := range catalog.All() {
		object, ok := objects[stateNames[spec.ClientID]]
		if !ok {
			return nil, fmt.Errorf("client state projection is missing for %s", spec.ClientID)
		}
		schema, err := jsonschema.ForType(object.GoType, nil)
		if err != nil {
			return nil, fmt.Errorf("infer %s schema: %w", object.Name, err)
		}
		schema.Schema = "https://json-schema.org/draft/2020-12/schema"
		schema.Title = object.Name
		if err := projectObjectSchema(schema, object, objectsByType); err != nil {
			return nil, err
		}
		encoded, err := json.Marshal(schema, json.Deterministic(true), jsontext.Multiline(true), jsontext.WithIndent("  "))
		if err != nil {
			return nil, fmt.Errorf("encode %s schema: %w", object.Name, err)
		}
		encoded = compactPrimitiveArrays(encoded, 100)
		encoded = append(encoded, '\n')
		path := filepath.Join("api", "contracts", spec.ClientID+".schema.json")
		outputs[path] = encoded
	}
	return outputs, nil
}

// projectObjectSchema applies the same field projection used by the generated
// TypeScript to the schema inferred from Go. jsonschema.ForType correctly
// captures the wire shape, but it cannot know that client projections exclude
// fields or intentionally make nested fields optional.
func projectObjectSchema(schema *jsonschema.Schema, object objectDef, objects map[reflect.Type]objectDef) error {
	allowed := make(map[string]fieldDef, len(object.Fields))
	order := make([]string, 0, len(object.Fields))
	required := make([]string, 0, len(object.Fields))
	for _, field := range object.Fields {
		allowed[field.JSONName] = field
		order = append(order, field.JSONName)
		if !field.Optional {
			required = append(required, field.JSONName)
		}
	}
	for name := range schema.Properties {
		if _, ok := allowed[name]; !ok {
			delete(schema.Properties, name)
		}
	}
	if len(schema.Properties) != len(allowed) {
		return fmt.Errorf("inferred %s schema has %d selected properties, want %d", object.Name, len(schema.Properties), len(allowed))
	}
	schema.PropertyOrder = order
	schema.Required = required

	for _, field := range object.Fields {
		goField, ok := findJSONField(object.GoType, field.JSONName)
		if !ok {
			return fmt.Errorf("contract %s exposes %q, which is absent from Go type %v", object.Name, field.JSONName, object.GoType)
		}
		property := schema.Properties[field.JSONName]
		if property == nil {
			return fmt.Errorf("inferred %s schema is missing property %q", object.Name, field.JSONName)
		}
		if !strings.Contains(field.TSType, " | null") {
			removeNullType(property)
		}
		if err := projectNestedSchema(property, goField.Type, objects); err != nil {
			return fmt.Errorf("project %s.%s schema: %w", object.Name, field.JSONName, err)
		}
		applyTypeScriptConstraint(property, field.TSType)
	}
	return nil
}

func projectNestedSchema(schema *jsonschema.Schema, goType reflect.Type, objects map[reflect.Type]objectDef) error {
	for goType.Kind() == reflect.Pointer {
		goType = goType.Elem()
	}
	if object, ok := objects[goType]; ok {
		return projectObjectSchema(schema, object, objects)
	}
	switch goType.Kind() {
	case reflect.Array, reflect.Slice:
		if schema.Items == nil {
			return errors.New("array schema has no item definition")
		}
		return projectNestedSchema(schema.Items, goType.Elem(), objects)
	default:
		return nil
	}
}

func removeNullType(schema *jsonschema.Schema) {
	if schema.Type == "null" {
		schema.Type = ""
	}
	if len(schema.Types) == 0 {
		return
	}
	types := make([]string, 0, len(schema.Types))
	for _, value := range schema.Types {
		if value != "null" {
			types = append(types, value)
		}
	}
	if len(types) == 1 {
		schema.Type, schema.Types = types[0], nil
		return
	}
	schema.Types = types
}

func applyTypeScriptConstraint(schema *jsonschema.Schema, tsType string) {
	values, ok := typeScriptEnum(tsType)
	if ok {
		schema.Enum = values
	}
}

func typeScriptEnum(tsType string) ([]any, bool) {
	tsType = strings.TrimSpace(tsType)
	if tsType == "" {
		return nil, false
	}
	includeNull := strings.HasSuffix(tsType, " | null")
	tsType = strings.TrimSuffix(tsType, " | null")
	for _, definition := range enumDefinitions() {
		if definition.Name != tsType {
			continue
		}
		values := make([]any, 0, len(definition.Values)+1)
		for _, value := range definition.Values {
			values = append(values, value)
		}
		if includeNull {
			values = append(values, nil)
		}
		return values, true
	}

	parts := strings.Split(tsType, " | ")
	values := make([]any, 0, len(parts)+1)
	for _, part := range parts {
		if strings.HasPrefix(part, `"`) {
			value, err := strconv.Unquote(part)
			if err != nil {
				return nil, false
			}
			values = append(values, value)
			continue
		}
		value, err := strconv.Atoi(part)
		if err != nil {
			return nil, false
		}
		values = append(values, value)
	}
	if includeNull {
		values = append(values, nil)
	}
	return values, len(values) > 0
}

func compactPrimitiveArrays(encoded []byte, width int) []byte {
	lines := strings.Split(string(encoded), "\n")
	result := make([]string, 0, len(lines))
	for index := 0; index < len(lines); {
		line := lines[index]
		trimmed := strings.TrimSpace(line)
		if !strings.HasSuffix(trimmed, "[") {
			result = append(result, line)
			index++
			continue
		}
		end := index + 1
		var values []string
		valid := false
		for ; end < len(lines); end++ {
			value := strings.TrimSpace(lines[end])
			if value == "]" || value == "]," {
				valid = len(values) > 0
				break
			}
			primitive := strings.TrimSuffix(value, ",")
			_, numericErr := strconv.ParseFloat(primitive, 64)
			quoted := strings.HasPrefix(primitive, `"`) && strings.HasSuffix(primitive, `"`)
			if !quoted && primitive != "true" && primitive != "false" && primitive != "null" && numericErr != nil {
				valid = false
				break
			}
			values = append(values, primitive)
		}
		if !valid || end >= len(lines) {
			result = append(result, line)
			index++
			continue
		}
		closing := strings.TrimSpace(lines[end])
		candidate := strings.TrimSuffix(line, "[") + "[" + strings.Join(values, ", ") + "]"
		if strings.HasSuffix(closing, ",") {
			candidate += ","
		}
		if len(candidate) > width {
			result = append(result, lines[index:end+1]...)
		} else {
			result = append(result, candidate)
		}
		index = end + 1
	}
	return []byte(strings.Join(result, "\n"))
}

func generateTypeScript() ([]byte, error) {
	var out bytes.Buffer
	out.WriteString(generatedHeader)
	out.WriteString("\nexport const AGENT_ORDER = [\n")
	for _, spec := range catalog.All() {
		fmt.Fprintf(&out, "  %q,\n", spec.ClientID)
	}
	out.WriteString("] as const;\n\n")
	out.WriteString("export type AgentId = (typeof AGENT_ORDER)[number];\n\n")
	out.WriteString("export const AGENT_BACKEND_PATHS = {\n")
	for _, spec := range catalog.All() {
		fmt.Fprintf(&out, "  %s: %q,\n", typeScriptProperty(spec.ClientID), spec.Route)
	}
	out.WriteString("} as const satisfies Record<AgentId, string>;\n")

	for _, enum := range enumDefinitions() {
		declaration := fmt.Sprintf("export type %s = %s;", enum.Name, quotedUnion(enum.Values))
		if len(declaration) <= 100 {
			fmt.Fprintf(&out, "\n%s\n", declaration)
			continue
		}
		fmt.Fprintf(&out, "\nexport type %s =\n", enum.Name)
		for index, value := range enum.Values {
			separator := ""
			if index == len(enum.Values)-1 {
				separator = ";"
			}
			fmt.Fprintf(&out, "  | %q%s\n", value, separator)
		}
	}
	out.WriteString("\nexport type TrendsCell = string | number | boolean | null;\n")
	out.WriteString("export type TrendsRow = Record<string, TrendsCell>;\n")

	objects := objectDefinitions()
	names := make(map[reflect.Type]string, len(objects))
	for _, object := range objects {
		if prior, exists := names[object.GoType]; exists {
			return nil, fmt.Errorf("go type %v is mapped to both %s and %s", object.GoType, prior, object.Name)
		}
		names[object.GoType] = object.Name
	}
	for _, object := range objects {
		if err := renderObject(&out, object, names); err != nil {
			return nil, err
		}
	}
	return out.Bytes(), nil
}

func renderObject(out *bytes.Buffer, object objectDef, names map[reflect.Type]string) error {
	if object.GoType.Kind() != reflect.Struct {
		return fmt.Errorf("contract %s uses non-struct Go type %v", object.Name, object.GoType)
	}
	fmt.Fprintf(out, "\nexport type %s = {\n", object.Name)
	seen := make(map[string]bool, len(object.Fields))
	for _, field := range object.Fields {
		if seen[field.JSONName] {
			return fmt.Errorf("contract %s repeats field %s", object.Name, field.JSONName)
		}
		seen[field.JSONName] = true
		goField, ok := findJSONField(object.GoType, field.JSONName)
		if !ok {
			return fmt.Errorf("contract %s exposes %q, which is absent from Go type %v", object.Name, field.JSONName, object.GoType)
		}
		tsType := field.TSType
		if tsType == "" {
			var err error
			tsType, err = inferTypeScript(goField.Type, names)
			if err != nil {
				return fmt.Errorf("contract %s field %s: %w", object.Name, field.JSONName, err)
			}
		}
		optional := ""
		if field.Optional {
			optional = "?"
		}
		fmt.Fprintf(out, "  %s%s: %s;\n", field.JSONName, optional, tsType)
	}
	out.WriteString("};\n")
	return nil
}

func findJSONField(goType reflect.Type, name string) (reflect.StructField, bool) {
	for i := range goType.NumField() {
		field := goType.Field(i)
		jsonName, _, _ := strings.Cut(field.Tag.Get("json"), ",")
		if jsonName == "" {
			jsonName = field.Name
		}
		if jsonName == name {
			return field, true
		}
	}
	return reflect.StructField{}, false
}

func inferTypeScript(goType reflect.Type, names map[reflect.Type]string) (string, error) {
	if name, ok := names[goType]; ok {
		return name, nil
	}
	switch goType.Kind() {
	case reflect.Pointer:
		return inferTypeScript(goType.Elem(), names)
	case reflect.Bool:
		return "boolean", nil
	case reflect.Int, reflect.Int8, reflect.Int16, reflect.Int32, reflect.Int64,
		reflect.Uint, reflect.Uint8, reflect.Uint16, reflect.Uint32, reflect.Uint64,
		reflect.Float32, reflect.Float64:
		return "number", nil
	case reflect.String:
		return "string", nil
	case reflect.Interface:
		return "unknown", nil
	case reflect.Slice, reflect.Array:
		element, err := inferTypeScript(goType.Elem(), names)
		if err != nil {
			return "", err
		}
		if strings.Contains(element, " | ") {
			element = "(" + element + ")"
		}
		return element + "[]", nil
	case reflect.Map:
		if goType.Key().Kind() != reflect.String {
			return "", fmt.Errorf("map key %v is not a string", goType.Key())
		}
		value, err := inferTypeScript(goType.Elem(), names)
		if err != nil {
			return "", err
		}
		return "Record<string, " + value + ">", nil
	default:
		return "", fmt.Errorf("unsupported Go type %v", goType)
	}
}

